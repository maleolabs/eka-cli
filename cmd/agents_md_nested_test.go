// cmd tests for `eka agents-md --nested`: the path-scoped projection of the
// binding index (M2, sto:path-scoped-projection). Fixtures reuse the
// agents-md source-only snapshot helpers (same package) and add tracked
// files + git so the nested rule (bindings from the snapshot, directories
// from `git ls-files`) is exercised end to end.

// nestedFixtureUnit builds one active fixture unit whose content carries an
// `appliesTo` declaration (the M1 scope field).
func nestedFixtureUnit(t *testing.T, typ, id, domain string, appliesTo ...string) *exchange.Unit {
	t.Helper()
	u := agentsMDFixtureUnit(typ, id, domain)
	payload, err := json.Marshal(map[string]any{"appliesTo": appliesTo})
	if err != nil {
		t.Fatal(err)
	}
	u.ContentPayload = payload
	return u
}

// writeTracked creates one file at repo-relative slash path.
func writeTracked(t *testing.T, repo, rel string) {
	t.Helper()
	p := filepath.Join(repo, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte("x\n"), 0o644); err != nil {
		t.Fatal(err)
	}
}

// nestedScopedRepo builds the AC3 fixture: two subtrees bound by DIFFERENT
// constraints, one subtree with a tracked file but no binding, a third
// subtree with no tracked file at all, and git initialized. It restores the
// real PATH for git.
func nestedScopedRepo(t *testing.T) string {
	t.Helper()
	if testOrigPath != "" {
		t.Setenv("PATH", testOrigPath)
	}
	repo := agentsMDRepo(t, []*exchange.Unit{
		nestedFixtureUnit(t, "adr", "x", "Architecture", "a/**"),
		nestedFixtureUnit(t, "fnd", "y", "Discovery", "b/**"),
		nestedFixtureUnit(t, "adr", "z", "Architecture", "never/**"), // matches no tracked path
	})
	writeTracked(t, repo, "a/f.txt")
	writeTracked(t, repo, "b/g.txt")
	writeTracked(t, repo, "c/plain.txt") // tracked, but no constraint binds c/
	gitInit(t, repo)
	return repo
}

// TestAgentsMDNestedScoped covers AC3 (subtrees name only their own
// constraints), AC4 (an unbound directory gets no file) and AC1
// (regeneration byte-identical; a hand-edited nested file fails --check).
func TestAgentsMDNestedScoped(t *testing.T) {
	repo := nestedScopedRepo(t)

	if code, _, errText := runIn([]string{"agents-md", "--nested", "--write"}); code != 0 {
		t.Fatalf("--nested --write: exit = %d, want 0\nstderr: %s", code, errText)
	}

	// AC3: each subtree names only its own constraint.
	aBlock := managedBlock(t, filepath.Join(repo, "a", "AGENTS.md"))
	if !strings.Contains(aBlock, "adr: x") || strings.Contains(aBlock, "fnd: y") {
		t.Errorf("a/AGENTS.md must name only adr: x:\n%s", aBlock)
	}
	bBlock := managedBlock(t, filepath.Join(repo, "b", "AGENTS.md"))
	if !strings.Contains(bBlock, "fnd: y") || strings.Contains(bBlock, "adr: x") {
		t.Errorf("b/AGENTS.md must name only fnd: y:\n%s", bBlock)
	}

	// AC4: no binding → no file; and root AGENTS.md is not generated by --nested.
	for _, absent := range []string{
		filepath.Join(repo, "c", "AGENTS.md"),
		filepath.Join(repo, "never", "AGENTS.md"),
		filepath.Join(repo, "AGENTS.md"),
	} {
		if _, err := os.Stat(absent); !os.IsNotExist(err) {
			t.Errorf("%s must not exist (stat err = %v)", absent, err)
		}
	}

	// AC1: regeneration is byte-identical and --check is current.
	beforeA, err := os.ReadFile(filepath.Join(repo, "a", "AGENTS.md"))
	if err != nil {
		t.Fatal(err)
	}
	if code, _, errText := runIn([]string{"agents-md", "--nested", "--write"}); code != 0 {
		t.Fatalf("second --write: exit = %d\nstderr: %s", code, errText)
	}
	afterA, _ := os.ReadFile(filepath.Join(repo, "a", "AGENTS.md"))
	if string(beforeA) != string(afterA) {
		t.Errorf("regeneration is not byte-identical:\n%q\n%q", beforeA, afterA)
	}
	if code, _, errText := runIn([]string{"agents-md", "--nested", "--check"}); code != 0 {
		t.Fatalf("--nested --check after --write: exit = %d, want 0\nstderr: %s", code, errText)
	}

	// AC1: a hand-edited nested managed region fails the check.
	drifted := strings.Replace(string(afterA), "adr: x", "adr: PERTURBED", 1)
	if drifted == string(afterA) {
		t.Fatal("perturbation did not change a/AGENTS.md")
	}
	if err := os.WriteFile(filepath.Join(repo, "a", "AGENTS.md"), []byte(drifted), 0o644); err != nil {
		t.Fatal(err)
	}
	if code, _, _ := runIn([]string{"agents-md", "--nested", "--check"}); code != 1 {
		t.Fatalf("--nested --check after hand-edit: exit = %d, want 1", code)
	}

	// JSON report is deterministic and carries the per-directory shape.
	_, j1, _ := runIn([]string{"agents-md", "--nested", "--check", "--json"})
	_, j2, _ := runIn([]string{"agents-md", "--nested", "--check", "--json"})
	if j1 != j2 {
		t.Errorf("nested json is not byte-stable:\n%q\n%q", j1, j2)
	}
	for _, want := range []string{`"nested":[`, `"file":"a/AGENTS.md"`, `"status":"drift"`, `"constraints":1`} {
		if !strings.Contains(j1, want) {
			t.Errorf("nested json missing %q:\n%s", want, j1)
		}
	}
}

// TestAgentsMDNestedStale covers the stale branch: a committed generated
// nested file whose bindings disappear is drift on --check and is removed on
// --write.
func TestAgentsMDNestedStale(t *testing.T) {
	if testOrigPath != "" {
		t.Setenv("PATH", testOrigPath)
	}
	unit := nestedFixtureUnit(t, "adr", "x", "Architecture", "a/**")
	repo := agentsMDRepo(t, []*exchange.Unit{unit})
	writeTracked(t, repo, "a/f.txt")
	gitInit(t, repo)
	if code, _, e := runIn([]string{"agents-md", "--nested", "--write"}); code != 0 {
		t.Fatalf("--nested --write: %s", e)
	}
	// Commit the projection so it is in the tracked set.
	add := exec.Command("git", "add", "-A")
	add.Dir = repo
	if out, err := add.CombinedOutput(); err != nil {
		t.Fatalf("git add: %v\n%s", err, out)
	}

	// Rebuild the snapshot WITHOUT the a/** binding: a/AGENTS.md is now stale.
	writeAgentsMDSnapshot(t, filepath.Join(repo, "exchange", "snapshots"),
		[]*exchange.Unit{agentsMDFixtureUnit("adr", "x", "Architecture")})
	code, _, errText := runIn([]string{"agents-md", "--nested", "--check"})
	if code != 1 {
		t.Fatalf("--nested --check with a stale file: exit = %d, want 1\n%s", code, errText)
	}
	if code, _, e := runIn([]string{"agents-md", "--nested", "--write"}); code != 0 {
		t.Fatalf("--nested --write removing stale: %s", e)
	}
	if _, err := os.Stat(filepath.Join(repo, "a", "AGENTS.md")); !os.IsNotExist(err) {
		t.Errorf("stale a/AGENTS.md must be removed (stat err = %v)", err)
	}
}

// TestAgentsMDNestedHostClaude covers AC2: --host claude writes the rule
// shims only when .claude/ is configured; without it the host is skipped and
// nothing is written. opencode is an acknowledged no-op.
func TestAgentsMDNestedHostClaude(t *testing.T) {
	if testOrigPath != "" {
		t.Setenv("PATH", testOrigPath)
	}
	unit := nestedFixtureUnit(t, "adr", "x", "Architecture", "a/**")

	t.Run("configured writes shims", func(t *testing.T) {
		repo := agentsMDRepo(t, []*exchange.Unit{unit})
		writeTracked(t, repo, "a/f.txt")
		if err := os.MkdirAll(filepath.Join(repo, ".claude"), 0o755); err != nil {
			t.Fatal(err)
		}
		gitInit(t, repo)
		if code, _, e := runIn([]string{"agents-md", "--nested", "--host", "claude", "--write"}); code != 0 {
			t.Fatalf("--host claude --write: exit = %d\n%s", code, e)
		}
		shim := filepath.Join(repo, ".claude", "rules", "a.md")
		raw, err := os.ReadFile(shim)
		if err != nil {
			t.Fatalf("claude shim not written: %v", err)
		}
		for _, want := range []string{"paths:", "- a/**", "adr: x", "eka get ea/<type>:<id>"} {
			if !strings.Contains(string(raw), want) {
				t.Errorf("shim missing %q:\n%s", want, raw)
			}
		}
		if code, _, e := runIn([]string{"agents-md", "--nested", "--host", "claude", "--check"}); code != 0 {
			t.Fatalf("--host claude --check: exit = %d\n%s", code, e)
		}
	})

	t.Run("unconfigured is skipped", func(t *testing.T) {
		repo := agentsMDRepo(t, []*exchange.Unit{unit})
		writeTracked(t, repo, "a/f.txt")
		gitInit(t, repo) // no .claude/
		code, _, errText := runIn([]string{"agents-md", "--nested", "--host", "claude", "--write"})
		if code != 0 {
			t.Fatalf("--host claude without .claude: exit = %d\n%s", code, errText)
		}
		if !strings.Contains(errText, "skipped") {
			t.Errorf("unconfigured host must be reported skipped:\n%s", errText)
		}
		if _, err := os.Stat(filepath.Join(repo, ".claude")); !os.IsNotExist(err) {
			t.Errorf("nothing may be written for an unconfigured host (stat err = %v)", err)
		}
	})

	t.Run("opencode is a no-op", func(t *testing.T) {
		repo := agentsMDRepo(t, []*exchange.Unit{unit})
		writeTracked(t, repo, "a/f.txt")
		gitInit(t, repo)
		code, out, _ := runIn([]string{"agents-md", "--nested", "--host", "opencode", "--write"})
		if code != 0 {
			t.Fatalf("--host opencode: exit = %d", code)
		}
		if !strings.Contains(out, "no-op") {
			t.Errorf("opencode must be an acknowledged no-op:\n%s", out)
		}
	})
}

// TestAgentsMDHostRequiresNested: --host without --nested is a usage error.
func TestAgentsMDHostRequiresNested(t *testing.T) {
	agentsMDRepo(t, nil)
	code, _, errText := runIn([]string{"agents-md", "--host", "claude", "--write"})
	if code != 2 {
		t.Fatalf("--host without --nested: exit = %d, want 2\n%s", code, errText)
	}
	if !strings.Contains(errText, "--host requires --nested") {
		t.Errorf("usage error must explain the requirement: %q", errText)
	}
}
